"""shared models for the contracts/ json schemas.

the model modules are generated by generate.py. this file is hand written.
"""

from typing import Any

from .event import Attacker, Event, Geo
from .raw_event import RawEvent
from .session_summary import SessionSummary
from .stats import Stats

__all__ = [
    "Attacker",
    "Event",
    "Geo",
    "RawEvent",
    "SessionSummary",
    "Stats",
    "parse_event",
    "parse_raw_event",
]


def parse_event(data: Any):
    """validate a public event dict or json string, return the typed variant."""
    if isinstance(data, (str, bytes)):
        return Event.model_validate_json(data).root
    return Event.model_validate(data).root


def parse_raw_event(data: Any):
    """validate a raw trap event dict or json string, return the typed variant."""
    if isinstance(data, (str, bytes)):
        return RawEvent.model_validate_json(data).root
    return RawEvent.model_validate(data).root
